"""What the shipped packs must *cover*, as opposed to how the matcher behaves.

``test_rules_regression.py`` pins the mechanism: that a swapped consonant is
refused, that a held-down letter is still caught, that every listed term still
fires. It is deliberately vocabulary-free -- it reads the packs at run time and
asserts properties of the predicate.

This file is the other half, and every corpus in it is a list of inputs that
were **confirmed to fire against a shipped pack** -- not inputs somebody thought
might be risky. The first version of this file was written the other way round
and passed while the packs hour-muted ``nagas`` (a Twilight Forest boss),
``nagar``, ``nagger``, ``ritard``, ``retards`` as an ordinary verb, ``bezny``
(``běžný`` de-accented), ``cukání``, ``cákání``, ``Cogan``, ``rákosníka`` (a reed
warbler), ``I'll stab you with my sword``, ``I'll shoot you with my bow``,
``I'm going to shoot up at the ghast``, ``kill yourself to respawn``, ``are you
naked or wearing armour`` and ``I've got your IP for the server``. It passed
because the corpus used ``shoot the skeleton`` instead of ``I'll shoot you with
my bow``, and ``I am naked`` instead of ``are you naked``. Every one of those is
now below.

A benign corpus alone cannot prove much: it also passes if ``_match_fuzzy``
returns ``None`` for everything. ``test_fuzzy_matching_is_alive`` is the control.

The token-level instrument is ``processor/bench/domain-corpus/fp_surface.py``,
which walks a word list through the real matcher. It needs a system dictionary,
so it runs on Linux rather than in CI. It is a required gate before a fuzzy
pattern changes -- but it is **not** sufficient, and it is worth knowing why
before trusting it. Run against the pre-fix patterns on 2026-07-29 it found
``fagot``/``fagots`` in both English dictionaries and ``cogan``/``cygan``/
``cákaný`` in ``cs_CZ.dic`` -- and it did *not* find ``nagas``, ``nagar``,
``nagger`` or ``ritard``, because a Twilight Forest boss, a place name, a derived
form and a music abbreviation are in no word dictionary. Those needed a second
corpus, generated by ``minecraft_vocabulary.py`` from the vendored
``minecraft-data`` package, which finds all of them.

So: three layers, none of which subsumes another. The dictionary sweep covers
ordinary vocabulary, the domain sweep covers game vocabulary, and this file
covers phrases -- a sweep is token-level and can say nothing about ``are you
naked or wearing armour``.

One trap in the sweep itself, learned the hard way: ``fp_surface.py`` defaults to
``--min-length 4`` and silently skips shorter tokens. The transcriber variants
added on 2026-07-30 include the three-character ``nga``, so the default run
reported a clean gate while never looking at the one addition that warranted
looking at. Pass ``--min-length 3`` whenever a pack contains a phrase shorter
than four characters. Re-run at 3: 73,268 American, 72,718 British, 256,477
Czech and 5,419 Minecraft tokens, nothing fires.

Nothing here spells a slur: the must-flag side is threat, grooming and abuse
phrasing, and the hate rules are covered by the regression suite reading terms
out of the packs.
"""

