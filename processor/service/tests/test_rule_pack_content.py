@pytest.mark.parametrize("language", LANGUAGES)
def test_consonant_marked_terms_ship_a_de_accented_twin(language: str) -> None:
    """The matcher folds vowel marks but not consonant ones, and the shipped
    transcriber drops both. A term carrying ``š``, ``č``, ``ř``, ``ž``, ``ť``,
    ``ď`` or ``ň`` therefore needs the unmarked spelling listed too --
    ``cigoška`` had none, and ``ta cigoska`` matched nothing."""
    for rule in pack(language).rules:
        if rule.match_type == "regex":
            continue
        listed = set(rule.patterns)
        for pattern in rule.patterns:
            # The twin the packs actually ship is fully unmarked, not
            # consonant-only: the transcriber that drops `š` drops `ů` too, so
            # `připoj se na můj server` pairs with `pripoj se na muj server`.
            twin = "".join(
                character
                for character in unicodedata.normalize("NFKD", pattern)
                if not unicodedata.combining(character)
            )
            if twin == pattern:
                continue
            assert twin in listed, (
                f"{rule.rule_id}: lists {pattern!r} but not the de-accented {twin!r}; "
                f"the matcher does not fold consonant marks and the transcriber drops them"
            )
