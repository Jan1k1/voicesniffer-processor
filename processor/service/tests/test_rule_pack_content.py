# ---------------------------------------------------------------------------
# The allow layer
# ---------------------------------------------------------------------------
# Cross-pack tier disagreements that are known, deliberate, and a different thing
# from the collisions the test below exists to catch.
#
# The collisions are two unrelated words that happen to be the same string:
# `pedra` is a homophobic inflection in Slovene and a stone in Portuguese,
# `pederast` is a slur in Estonian and the clinical term in Romanian. Neither
# pack is wrong; the merge is. Those were fixed by moving the string to review
# tier in the pack that muted it.
#
# These are not that. Every entry below is the *same word in the same sense*,
# with two packs disagreeing about how offensive it is to their own speakers --
# `neger` is at review tier in Hungarian, Slovak and Estonian because the older
# generation used it neutrally, and at mute tier in Danish, German, Dutch and
# Swedish because it is the slur outright there. Harmonising them is a register
# question for a native speaker of each language, not something a matcher or a
# sweep can settle, and both answers are defensible.
#
# So they are frozen rather than fixed: the set cannot grow without somebody
# writing down why, and the day a native reviewer settles one of these, the entry
# comes out.
KNOWN_TIER_DISAGREEMENTS = frozenset(
    {
        # `neger` and its spellings. en reaches it through the *fuzzy* nword rule
        # rather than by listing it, which is worth knowing: `neger` is two
        # accepted drifts from `nigger`.
        ("et", "neeger", "en"),
        ("hu", "neger", "da"),
        ("hu", "neger", "de"),
        ("hu", "neger", "en"),
        ("hu", "neger", "nl"),
        ("hu", "neger", "sv"),
        ("hu", "néger", "en"),
        ("sk", "neger", "da"),
        ("sk", "neger", "de"),
        ("sk", "neger", "en"),
        ("sk", "neger", "nl"),
        ("sk", "neger", "sv"),
        # The Roma pejorative: hr holds it at review tier, cs and sk act on it.
        ("hr", "cigos", "cs"),
        ("hr", "cigoš", "cs"),
        ("hr", "cigos", "sk"),
        ("hr", "cigoš", "sk"),
    }
)


@pytest.mark.parametrize("language", LANGUAGES)
def test_no_review_tier_pattern_is_muted_by_a_different_pack(language: str) -> None:
    """The cross-language half of the test above, and the one that was missing.

    ``test_a_review_tier_pattern_alone_never_reaches_an_automatic_action`` asks
    each pack about its own review patterns. But ``languages: [auto]`` runs
    *every* pack against *every* utterance and merges the matches
    (``app._match_transcript``), so a word one pack deliberately holds at review
    tier is muted anyway if another pack lists it at mute tier. That is not a
    theoretical shape: it is `pedra`, correct Slovene and the Portuguese for
    stone; `cigo`, held at review tier by hr and sl and muted by hu; and
    `pederast`, held at review tier by ro and muted by et -- which nobody
    reported and this test found.

    A review-tier decision is a claim about a word, not about a file. If one pack
    can override another's, the decision means nothing.

    ``KNOWN_TIER_DISAGREEMENTS`` above carves out the cases where two packs mean
    the same word and disagree about its register, which is a different problem
    and not one this test can decide.
    """
    loaded = pack(language)
    review = {
        pattern
        for rule in loaded.rules
        if rule.context_required and rule.match_type != "regex"
        for pattern in rule.patterns
        if " " not in pattern
    }

    for other in LANGUAGES:
        if other == language:
            continue
        matcher = pack(other)
        for pattern in sorted(review):
            if (language, pattern, other) in KNOWN_TIER_DISAGREEMENTS:
                continue
            acting = [
                match.rule_id
                for match in matcher.match(pattern).matches
                if not match.context_required
            ]
            assert not acting, (
                f"{language}.yml holds {pattern!r} at review tier and {other}.yml mutes "
                f"for it ({acting}); under `languages: [auto]` both packs answer the "
                f"same utterance, so the review-tier decision does not hold"
            )


def test_every_known_tier_disagreement_is_still_real() -> None:
    """A carve-out that carves nothing out is a documented problem that no longer
    exists, reading as a live one. Same argument as
    ``test_every_allow_entry_actually_suppresses_something``."""
    for language, pattern, other in sorted(KNOWN_TIER_DISAGREEMENTS):
        rule = rule_for(language, pattern)
        assert rule is not None and rule.context_required, (
            f"{pattern!r} is no longer at review tier in {language}.yml; drop the carve-out"
        )
        acting = [
            match.rule_id
            for match in pack(other).match(pattern).matches
            if not match.context_required
        ]
        assert acting, (
            f"{other}.yml no longer acts on {pattern!r}; the disagreement is settled, "
            f"drop the carve-out"
        )


