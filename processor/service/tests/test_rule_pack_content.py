def pack(language: str) -> RulePack:
    return RulePack.load(RULES_DIRECTORY / f"{language}.yml")


def rule_for(language: str, pattern: str):
    for rule in pack(language).rules:
        if pattern in rule.patterns:
            return rule
    return None


