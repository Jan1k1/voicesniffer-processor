@pytest.mark.parametrize("language", LANGUAGES)
def test_fuzzy_patterns_have_no_adjacent_distinct_vowels(language: str) -> None:
    """Run structure is compared only when the run *counts* are equal. Two
    adjacent different vowels break that for one specific drift: swapping one
    into the other merges two runs. The pattern is not dead -- an exact token
    still matches -- but its tolerance is uneven in a way nothing else reports,
    so such patterns are listed as `exact` instead."""
    for rule in pack(language).rules:
        if rule.match_type != "fuzzy":
            continue
        for pattern in rule.patterns:
            for index in range(len(pattern) - 1):
                left, right = pattern[index], pattern[index + 1]
                assert not (_is_vowel(left) and _is_vowel(right) and left != right), (
                    f"{rule.rule_id}: fuzzy pattern {pattern!r} has adjacent distinct vowels "
                    f"{left!r}{right!r}; list it as `exact` instead"
                )


def test_contractions_ship_both_spellings() -> None:
    """``I'll`` normalises to ``i ll`` but ``Ill`` normalises to ``ill``, and the
    transcriber emits both. Checked in both directions from named pairs: the
    first version only walked spaced -> joined, so a rule listing only ``ill
    shoot you`` passed while ``I'll shoot you`` missed.

    English only. Czech writes no apostrophe contractions and the fragments are
    ordinary Czech prepositions, so the heuristic there asks for nonsense."""
    for rule in pack("en").rules:
        if rule.match_type == "regex":
            continue
        listed = set(rule.patterns)
        for pattern in rule.patterns:
            for spaced, joined in CONTRACTION_PAIRS:
                if pattern.startswith(f"{spaced} ") or f" {spaced} " in pattern:
                    twin = pattern.replace(f"{spaced} ", f"{joined} ", 1)
                elif pattern.startswith(f"{joined} ") or f" {joined} " in pattern:
                    twin = pattern.replace(f"{joined} ", f"{spaced} ", 1)
                else:
                    continue
                assert twin in listed, (
                    f"{rule.rule_id}: lists {pattern!r} but not {twin!r}; "
                    f"the transcriber emits both spellings of {spaced!r}/{joined!r}"
                )


