# ---------------------------------------------------------------------------
# Coverage, proved by an input rather than by metadata
# ---------------------------------------------------------------------------
@pytest.mark.parametrize("language", LANGUAGES)
def _fires_on_own_terms(loaded: RulePack, rule) -> bool:
    """Does this rule actually match something it itself lists?

    Regex rules are excluded because the loader already proves it for them: a
    regex rule must carry a ``probe`` that is verified to match after
    normalisation, and the probe is not kept on the parsed rule to replay here.
    """
    return any(
        any(match.rule_id == rule.rule_id for match in loaded.match(pattern).matches)
        for pattern in rule.patterns
    )


@pytest.mark.parametrize("language", LANGUAGES)
def test_every_rule_fires_on_its_own_terms(language: str) -> None:
    """A rule that cannot match anything is worse than no rule: it reads as
    coverage.

    This replaced a pair of tests that asked every pack to flag a corpus of
    English or Czech sentences, chosen by ``if language == "en" else``. That was
    fine while the packs were English and Czech. Once the directory held
    twenty-three languages it demanded that a Polish pack flag Czech utterances,
    which is unsatisfiable without putting Czech phrases in the Polish pack, and
    that is precisely the cross-language false positive these packs exist to
    avoid. Reachability is a property of a pack against its own vocabulary, so
    it is now asked that way. Whether a *realistic sentence* reaches a rule stays
    language-specific, in the must-flag tests below.
    """
    loaded = pack(language)

    dead = [
        rule.rule_id
        for rule in loaded.rules
        if rule.match_type != "regex" and not _fires_on_own_terms(loaded, rule)
    ]

    assert dead == [], f"{language}: rules that match none of their own terms: {dead}"


@pytest.mark.parametrize("language", LANGUAGES)
def test_every_declared_category_and_severity_is_reachable(language: str) -> None:
    """Declaring a category is free. Reaching it is the claim worth testing."""
    loaded = pack(language)

    declared_categories = {rule.category for rule in loaded.rules if not rule.context_required}
    declared_severities = {rule.severity for rule in loaded.rules if not rule.context_required}
    reached_categories: set[str] = set()
    reached_severities: set[int] = set()
    for rule in loaded.rules:
        if rule.context_required or rule.match_type == "regex":
            continue
        for pattern in rule.patterns:
            verdict = loaded.match(pattern)
            for match in verdict.matches:
                if match.rule_id == rule.rule_id and not match.context_required:
                    reached_categories.add(match.category)
                    reached_severities.add(match.severity)

    assert declared_categories <= reached_categories | {
        rule.category for rule in loaded.rules if rule.match_type == "regex"
    }, f"{language}: declared but unreachable categories"
    assert declared_severities <= reached_severities | {
        rule.severity for rule in loaded.rules if rule.match_type == "regex"
    }, f"{language}: declared but unreachable severities"


